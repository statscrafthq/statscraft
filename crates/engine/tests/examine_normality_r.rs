fn number(cell: &Cell) -> f64 {
    match cell {
        Cell::Number(n) => *n,
        other => panic!("{other:?} is no number"),
    }
}

#[test]
fn shapiro_wilk_and_the_kolmogorov_smirnov_statistic_agree_with_r() {
    let names = "v3 v4 v5 v7 v11 v12 v20 v35 v60 v100 v300";
    let (commands, errors) = parse(&format!(
        "{DATA}EXAMINE VARIABLES={names} /PLOT=NPPLOT /STATISTICS=NONE /MISSING=PAIRWISE."
    ));
    assert!(errors.is_empty(), "{errors:?}");
    let mut engine = Engine::default();
    let mut tables: Vec<Table> = Vec::new();
    for command in &commands {
        tables.extend(engine.execute(&command.command).expect("runs"));
    }
    let table: &Table = tables
        .iter()
        .find(|t| t.title.starts_with("Tests of Normality"))
        .expect("the table");
    // variable, K-S statistic, W, significance of W, n
    let expected = [
        ("v3", 0.324113824798, 0.876673724855, 0.31468637216, 3.0),
        ("v4", 0.291463953076, 0.8542560136, 0.240243892235, 4.0),
        ("v5", 0.227610215372, 0.871781476737, 0.273712413081, 5.0),
        ("v7", 0.291759293918, 0.863862337184, 0.163887089306, 7.0),
        ("v11", 0.152870191357, 0.952344440409, 0.67402139338, 11.0),
        ("v12", 0.201166284177, 0.84584817146, 0.0326373325633, 12.0),
        (
            "v20",
            0.172779232428,
            0.837585474195,
            0.00332496402264,
            20.0,
        ),
        ("v35", 0.129381204821, 0.96594258358, 0.341808271174, 35.0),
        (
            "v60",
            0.203588920795,
            0.797106434798,
            1.14439982998e-07,
            60.0,
        ),
        (
            "v100",
            0.147799920856,
            0.85555885857,
            1.91343747174e-08,
            100.0,
        ),
        (
            "v300",
            0.163576908798,
            0.798931200249,
            5.72659479697e-19,
            300.0,
        ),
    ];
    assert_eq!(table.rows.len(), expected.len());
    for (row, (name, d, w, p, n)) in table.rows.iter().zip(expected) {
        assert!(matches!(&row[0], Cell::Text(s) if s == name), "{name}");
        assert!(
            (number(&row[1]) - d).abs() < 1e-9,
            "{name} D: {:?} vs {d}",
            row[1]
        );
        assert!((number(&row[2]) - n).abs() < 1e-12, "{name} df");
        assert!(
            (number(&row[4]) - w).abs() < 1e-9,
            "{name} W: {:?} vs {w}",
            row[4]
        );
        assert!((number(&row[5]) - n).abs() < 1e-12, "{name} df");
        // the significance of W: 1e-9 absolute, which also holds for the 1e-19 of n = 300
        assert!(
            (number(&row[6]) - p).abs() < 1e-9,
            "{name} p: {:?} vs {p}",
            row[6]
        );
    }
}
