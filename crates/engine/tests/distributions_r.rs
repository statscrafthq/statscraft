/// The relative tolerance of a call: 1e-8 everywhere, except the noncentral t, which the engine
/// integrates to an absolute 1e-16 (the values compared here reach 1e-8), and the studentized
/// range, whose R function is itself accurate to about 1e-8 and whose inverse is taken here as
/// the root of it.
fn tolerance(call: &str) -> f64 {
    if call.contains("SRANGE") {
        1e-6
    } else if call.starts_with("NCDF.T") || call.starts_with("NPDF.T") {
        1e-7
    } else {
        1e-8
    }
}

#[test]
fn the_distribution_functions_agree_with_r_in_the_tails_too() {
    let mut engine = Engine::default();
    let setup = "DATA LIST FREE /x.\nBEGIN DATA\n1\nEND DATA.\n";
    let (commands, errors) = parse(setup);
    assert!(errors.is_empty());
    for c in &commands {
        engine.execute(&c.command).expect("data");
    }
    let mut bad = Vec::new();
    for (i, (call, want)) in GRID.iter().enumerate() {
        let (commands, errors) = parse(&format!("COMPUTE v{i} = {call}."));
        assert!(errors.is_empty(), "{call}: {errors:?}");
        let got = match engine.execute(&commands[0].command) {
            Ok(_) => engine
                .dataset()
                .unwrap()
                .variable(&format!("v{i}"))
                .unwrap()
                .numeric()
                .unwrap()
                .get(0),
            Err(e) => {
                bad.push(format!("{call}: error {e}"));
                continue;
            }
        };
        match got {
            Some(g) if (g - want).abs() <= tolerance(call) * want.abs() + 1e-300 => {}
            other => bad.push(format!("{call}: {other:?} against {want:e}")),
        }
    }
    assert!(
        bad.is_empty(),
        "{} of {} differ:\n{}",
        bad.len(),
        GRID.len(),
        bad.join("\n")
    );
}
