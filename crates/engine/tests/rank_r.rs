#[test]
fn rank_agrees_with_r() {
    let mut failures = Vec::new();
    for run in RUNS {
        let source = format!("{DATA}{}\n{}", run.weight, run.command);
        let (commands, errors) = parse(&source);
        if !errors.is_empty() {
            failures.push(format!("{}: {errors:?}", run.label));
            continue;
        }
        let mut engine = Engine::default();
        let mut failed = None;
        for command in &commands {
            if let Err(error) = engine.execute(&command.command) {
                failed = Some(format!("line {}: {error}", command.first_line));
                break;
            }
        }
        if let Some(error) = failed {
            failures.push(format!("{}: {error}", run.label));
            continue;
        }
        let data = engine.dataset().unwrap();
        for (name, want) in run.expected {
            let Ok(variable) = data.variable(name) else {
                failures.push(format!("{}: no variable {name}", run.label));
                continue;
            };
            let values = variable.numeric().unwrap();
            assert_eq!(data.case_count(), want.len(), "{}: {name}", run.label);
            for (case, want) in want.iter().enumerate() {
                let got = values.get(case);
                let same = match got {
                    None => want.is_nan(),
                    Some(got) => (got - want).abs() <= 1e-9 * want.abs().max(1.0),
                };
                if !same {
                    failures.push(format!(
                        "{}: {name} of case {} is {got:?}, R has {want}",
                        run.label,
                        case + 1
                    ));
                }
            }
        }
    }
    assert!(
        failures.is_empty(),
        "{} differ:\n{}",
        failures.len(),
        failures.join("\n")
    );
}
