fn run(data: &str, syntax: &str) -> (Engine, Vec<Table>) {
    let mut engine = Engine::default();
    let (commands, errors) = parse(&format!("{data}{syntax}"));
    assert!(errors.is_empty(), "{errors:?}");
    let mut tables = Vec::new();
    for command in &commands {
        match engine.execute(&command.command) {
            Ok(more) => tables.extend(more),
            Err(error) => panic!("line {}: {error}", command.first_line),
        }
    }
    (engine, tables)
}

/// The partition of the cases as the first-met label of each case, e.g. "11222".
fn partition(engine: &Engine, name: &str) -> String {
    let data = engine.dataset().unwrap();
    let Values::Numeric(col) = data.variable(name).unwrap().values() else {
        panic!("{name} is a string")
    };
    let mut seen: Vec<i64> = Vec::new();
    (0..data.case_count())
        .map(|k| {
            let v = col.get(k).expect("a cluster") as i64;
            let at = seen.iter().position(|s| *s == v).unwrap_or_else(|| {
                seen.push(v);
                seen.len() - 1
            });
            char::from(b'1' + at as u8)
        })
        .collect()
}

fn check(
    data: &str,
    variables: &str,
    measure: &str,
    method: &str,
    schedule: &[f64],
    partitions: &[&str; 3],
) {
    let (engine, tables) = run(
        data,
        &format!(
            "CLUSTER {variables} /MEASURE={measure} /METHOD={method} /PRINT=SCHEDULE /SAVE=CLUSTER(2,4)."
        ),
    );
    let t = tables
        .iter()
        .find(|t| t.title == "Agglomeration Schedule")
        .expect("schedule");
    assert_eq!(t.rows.len(), schedule.len(), "{measure} {method}");
    for (stage, (row, want)) in t.rows.iter().zip(schedule).enumerate() {
        let Cell::Number(got) = row[3] else {
            panic!("no coefficient")
        };
        assert!(
            (got - want).abs() <= 1e-8 + 1e-7 * want.abs(),
            "{measure} {method} stage {}: {got} is not {want}",
            stage + 1
        );
    }
    let tied = schedule.windows(2).any(|w| (w[0] - w[1]).abs() < 1e-9);
    if !tied {
        for (k, want) in [2, 3, 4].iter().zip(partitions) {
            assert_eq!(
                &partition(&engine, &format!("CLU{k}_1")),
                want,
                "{measure} {method} {k} clusters"
            );
        }
    }
}

