//! The date and string functions of COMPUTE against R and the rules of the guide.
//!
//! Dates are seconds since 14 October 1582, so R's `as.Date` with that origin gives the
//! expected values: DATE.DMY, DATE.MDY, DATE.MOYR, DATE.QYR, DATE.WKYR and DATE.YRDAY with the
//! days that roll into the next month (day 31 of September is 1 October, day 0 the last day of
//! the month before, month 13 January of the next year) and the arguments that make the result
//! system-missing; YRMODA (a day number, 99 meaning 1999); TIME.HMS and TIME.DAYS; CTIME.*;
//! XDATE.* of datetimes (the week counts from 1 January, so January 1 to 7 is week 1, the
//! weekday 1 is Sunday); DATEDIFF in every unit (a year or month is complete once the day of the
//! month and the time of the day are reached, the recorded choice where the guide leaves the end
//! of a long month open); DATESUM with the closest and the rollover method and a fraction
//! truncated for years, quarters and months. The guide's rules are written out in R where R has
//! no function for them, as RND was.
//!
//! Strings: `regexpr`, `substr`, `nchar` in characters and in bytes, `sub`, `toupper` and
//! `tolower`, `sprintf`, with a few characters of two and three bytes (é, 日) so that the
//! character functions (CHAR.*) and the byte functions (LENGTH, STRUNC, MBLEN.BYTE) part where
//! they should; INDEX, RINDEX, SUBSTR, LPAD and RPAD count characters like their CHAR forms, the
//! recorded choice of 2026-11-12 (the guide has them count bytes and calls them deprecated); a
//! divisor splits the needle of an index into blocks and the first (last) block found counts;
//! REPLACE with a count; STRUNC drops a fragment of a character; STRING and NUMBER with F, N and
//! COMMA formats, a number that does not fit written as asterisks (a pad of several characters
//! adds only whole copies and NUMBER reads as many characters as the format is wide, both as the
//! guide says; the F format also drops the zero before the decimal point, as the other tests and
//! the recorded choices have it: .50, not 0.50). A string variable shows no trailing
//! blanks, so the length of a padded or truncated result is checked as a number (LENGTH of RPAD
//! and STRUNC) beside its text.

