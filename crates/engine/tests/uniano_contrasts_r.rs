//! interval of each contrast (K matrix results) and the test of the whole set; the lack of fit
//! test (main effects only, the pure error from the replicates in the cells); and the saved case
//! statistics (predicted, residual, standardized, studentized, Cook, leverage, standard error of
//! the prediction and deleted residual) with and without a regression weight (the deleted residual
