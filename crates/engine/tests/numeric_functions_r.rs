/// 1e-12 relative, plus an absolute 1e-15 for a sine or cosine near a zero and for LNGAMMA near
/// its zeros at 1 and 2.
fn close(call: &str, got: f64, want: f64) -> bool {
    let absolute =
        if call.starts_with("SIN") || call.starts_with("COS") || call.starts_with("LNGAMMA") {
            1e-15
        } else {
            0.0
        };
    // a whole number below 1e15 is exact: a unit that was not truncated must not hide in the
    // tolerance. Values near 1e15 and above are not tested for RND and TRUNC on purpose: there
    // the fuzz bits, which grow with the value, reach more than half a unit.
    if want.fract() == 0.0 && want.abs() < 1e15 {
        return got == want;
    }
    (got - want).abs() <= 1e-12 * want.abs() + absolute + 1e-300
}

#[test]
fn the_numeric_functions_agree_with_r_with_missing_values_and_extremes() {
    let mut engine = Engine::default();
    let (commands, errors) = parse("DATA LIST FREE /x.\nBEGIN DATA\n1\nEND DATA.\n");
    assert!(errors.is_empty());
    for c in &commands {
        engine.execute(&c.command).expect("data");
    }
    let mut bad = Vec::new();
    for (i, (call, want)) in GRID.iter().enumerate() {
        let (commands, errors) = parse(&format!("COMPUTE v{i} = {call}."));
        assert!(errors.is_empty(), "{call}: {errors:?}");
        let got = match engine.execute(&commands[0].command) {
            Ok(_) => engine
                .dataset()
                .unwrap()
                .variable(&format!("v{i}"))
                .unwrap()
                .numeric()
                .unwrap()
                .get(0),
            Err(e) => {
                bad.push(format!("{call}: error {e}"));
                continue;
            }
        };
        let fine = match got {
            None => want.is_nan(),
            Some(g) => !want.is_nan() && close(call, g, *want),
        };
        if !fine {
            bad.push(format!("{call}: {got:?} against {want:e}"));
        }
    }
    assert!(
        bad.is_empty(),
        "{} of {} differ:\n{}",
        bad.len(),
        GRID.len(),
        bad.join("\n")
    );
}
