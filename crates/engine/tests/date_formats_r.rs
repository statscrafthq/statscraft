fn execute(engine: &mut Engine, source: &str) -> Result<(), String> {
    let (commands, errors) = parse(source);
    if let Some(error) = errors.first() {
        return Err(error.message.clone());
    }
    for c in &commands {
        engine.execute(&c.command).map_err(|e| e.to_string())?;
    }
    Ok(())
}

#[test]
fn writing_agrees_with_r() {
    let mut engine = Engine::default();
    execute(
        &mut engine,
        "DATA LIST FREE /x.\nBEGIN DATA\n1\nEND DATA.\nSTRING s (A60).\n",
    )
    .unwrap();
    let mut bad = Vec::new();
    for (format, value, want) in WRITES {
        if let Err(e) = execute(
            &mut engine,
            &format!("COMPUTE s = STRING({value}, {format})."),
        ) {
            bad.push(format!("{format} {value}: error {e}"));
            continue;
        }
        let got = engine
            .dataset()
            .unwrap()
            .variable("s")
            .unwrap()
            .string()
            .unwrap()
            .get(0)
            .to_string();
        if got != *want {
            bad.push(format!("{format} of {value}: {got:?} against {want:?}"));
        }
    }
    assert!(
        bad.is_empty(),
        "{} of {} differ:\n{}",
        bad.len(),
        WRITES.len(),
        bad.join("\n")
    );
}

#[test]
fn reading_agrees_with_r() {
    let mut bad = Vec::new();
    for (format, text, want) in READS {
        let mut engine = Engine::default();
        let source = format!(
            "SET EPOCH=1969.\nDATA LIST FIXED /v 1-40 ({format}) k 41 (F1).\nBEGIN DATA\n{text:<40}1\nEND DATA.\n"
        );
        if let Err(e) = execute(&mut engine, &source) {
            bad.push(format!("{format} {text:?}: error {e}"));
            continue;
        }
        let data = engine.dataset().unwrap();
        let got = data.variable("v").unwrap().numeric().unwrap().get(0);
        let fine = match got {
            None => want.is_nan(),
            Some(g) => !want.is_nan() && (g - want).abs() < 1e-6,
        };
        if !fine {
            bad.push(format!("{format} {text:?}: {got:?} against {want}"));
        }
    }
    assert!(
        bad.is_empty(),
        "{} of {} differ:\n{}",
        bad.len(),
        READS.len(),
        bad.join("\n")
    );
}

#[test]
fn alter_type_reads_the_new_formats_from_strings() {
    let mut engine = Engine::default();
    let source = "SET EPOCH=1969.\n\
        DATA LIST FIXED /a 1-12 (A) b 13-24 (A) c 25-36 (A).\n\
        BEGIN DATA\n\
        2Q95        Oct 2003    2003256\n\
        END DATA.\n\
        ALTER TYPE a (A12 = QYR12) b (A12 = MOYR12) c (A12 = JDATE12).\n\
        COMPUTE ok = a = DATE.DMY(1, 4, 1995) AND b = DATE.DMY(1, 10, 2003) AND c = DATE.DMY(13, 9, 2003).\n";
    execute(&mut engine, source).unwrap();
    let ok = engine
        .dataset()
        .unwrap()
        .variable("ok")
        .unwrap()
        .numeric()
        .unwrap()
        .get(0);
    assert_eq!(ok, Some(1.0));
}
