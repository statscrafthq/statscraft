//! CREATE (CSUM, DIFF, SDIFF, LAG, LEAD, MA, RMED, PMA), SHIFT VALUES and RMV against R on 30
//! invented cases with embedded, leading and trailing gaps, a user-missing code, SPLIT FILE
//! groups and TSET MISSING=INCLUDE. Spans odd and even, with minimum spans of every parity
//! (an even minimum under an odd span, and the other way round, takes the next higher span),
//! lags and leads from 1 to past the length of the series, offsets both ways, MEAN and MEDIAN
//! with spans 1, 2, 3, 5 and ALL, LINT, SMEAN and TREND.
//! What R computes itself: `stats::filter` (centered and prior means), `embed` with `median`
//! (running medians), `approx` (LINT), `lm` (TREND), subtraction for DIFF and SDIFF. What
//! follows the manual's rules, written out in the R script: each run between gaps is a series
//! of its own, the span that does not fit shrinks to the largest one that does and still
//! reaches the minimum, MEAN and MEDIAN need the span's number of valid values on each side
//! (estimates never feed on estimates), each split group is a series of its own. Series of 5
//! cases are shorter than some spans, lags and periods, which leaves everything missing; the
//! last two cases (no valid value, one valid value) are worked out by hand from the same rules,
//! as R has no counterpart for an estimate from nothing.

