fn run(syntax: &str) -> Vec<Table> {
    run_on(DATA, syntax)
}

fn run_on(data: &str, syntax: &str) -> Vec<Table> {
    let mut engine = Engine::default();
    let (commands, errors) = parse(&format!("{data}{syntax}"));
    assert!(errors.is_empty(), "{errors:?}");
    let mut tables = Vec::new();
    for command in &commands {
        match engine.execute(&command.command) {
            Ok(more) => tables.extend(more),
            Err(error) => panic!("line {}: {error}", command.first_line),
        }
    }
    tables
}

/// The row headers joined with " / ", an empty header taking the one above it.
fn row_keys(table: &Table) -> Vec<String> {
    let mut carried = vec![String::new(); table.row_headers];
    table
        .rows
        .iter()
        .map(|row| {
            for (level, cell) in row.iter().take(table.row_headers).enumerate() {
                let shown = match cell {
                    Cell::Text(t) if !t.is_empty() => Some(t.clone()),
                    Cell::Number(n) => Some(format!("{n}")),
                    _ => None,
                };
                if let Some(t) = shown {
                    carried[level] = t;
                    for deeper in carried.iter_mut().skip(level + 1) {
                        deeper.clear();
                    }
                }
            }
            carried
                .iter()
                .filter(|s| !s.is_empty())
                .cloned()
                .collect::<Vec<_>>()
                .join(" / ")
        })
        .collect()
}

fn value(tables: &[Table], title: &str, row: &str, column: &str) -> f64 {
    let table = tables
        .iter()
        .find(|t| t.title == title)
        .unwrap_or_else(|| panic!("no table {title}"));
    let r = row_keys(table)
        .iter()
        .position(|k| k == row)
        .unwrap_or_else(|| panic!("{title}: no row {row} in {:?}", row_keys(table)));
    let c = table
        .column_titles()
        .iter()
        .position(|t| t == column)
        .unwrap_or_else(|| panic!("{title}: no column {column} in {:?}", table.column_titles()));
    match &table.rows[r][c] {
        Cell::Number(n) => *n,
        other => panic!("{title} / {row} / {column}: {other:?}"),
    }
}

fn near(actual: f64, expected: f64, what: &str) {
    assert!(
        (actual - expected).abs() <= 1e-8 + 1e-7 * expected.abs(),
        "{what}: {actual} is not {expected}"
    );
}

fn expect(t: &[Table], title: &str, columns: &[&str], rows: &[(&str, &[f64])]) {
    for (key, values) in rows {
        for (column, want) in columns.iter().zip(values.iter()) {
            if !want.is_nan() {
                near(
                    value(t, title, key, column),
                    *want,
                    &format!("{title} / {key} / {column}"),
                );
            }
        }
    }
}

const EFFECTS: [(&str, &str); 3] = [
    ("time", "time * g"),
    ("task", "task * g"),
    ("time * task", "time * task * g"),
];

/// One choice of contrasts for time and task: the tests of the within-subjects contrasts of each
/// effect (per combination of contrasts: the effect's SS, F, p, its interaction with g: SS, F, p,
/// the error SS and MS) and the multivariate tests, which do not depend on the contrast
/// (Pillai's trace, Wilks' lambda, F, df, p; the main effect, then its interaction with g).
fn check(
    clause: &str,
    time: &[&str],
    task: &[&str],
    contrasts: &[[f64; 8]],
    multivariate: &[[f64; 6]],
) {
    let t = run(&format!("GLM y1 y2 y3 y4 y5 y6 BY g /WSFACTOR={clause}."));
    let mut names: Vec<Vec<String>> = vec![time.iter().map(|s| s.to_string()).collect()];
    names.push(task.iter().map(|s| s.to_string()).collect());
    let mut both = Vec::new();
    for a in time {
        for b in task {
            both.push(format!("{a} * {b}"));
        }
    }
    names.push(both);
    let mut at = 0;
    for (e, (effect, interaction)) in EFFECTS.iter().enumerate() {
        for name in &names[e] {
            let w = contrasts[at];
            at += 1;
            let get = |source: &str, c: &str| {
                value(
                    &t,
                    "Tests of Within-Subjects Contrasts",
                    &format!("{source} / {name}"),
                    c,
                )
            };
            let what = format!("{clause}: {effect} {name}");
            near(get(effect, "Type III Sum of Squares"), w[0], &what);
            near(get(effect, "F"), w[1], &what);
            near(get(effect, "Sig."), w[2], &what);
            near(get(interaction, "Type III Sum of Squares"), w[3], &what);
            near(get(interaction, "F"), w[4], &what);
            near(get(interaction, "Sig."), w[5], &what);
            let error = format!("Error({effect})");
            near(get(&error, "Type III Sum of Squares"), w[6], &what);
            near(get(&error, "Mean Square"), w[7], &what);
        }
    }
    assert_eq!(at, contrasts.len());
    for (k, (effect, interaction)) in EFFECTS.iter().enumerate() {
        for (source, w) in [
            (effect, multivariate[2 * k]),
            (interaction, multivariate[2 * k + 1]),
        ] {
            for (test, v) in [("Pillai's Trace", w[0]), ("Wilks' Lambda", w[1])] {
                let key = format!("{source} / {test}");
                let what = format!("{clause}: {key}");
                near(value(&t, "Multivariate Tests", &key, "Value"), v, &what);
                near(value(&t, "Multivariate Tests", &key, "F"), w[2], &what);
                near(
                    value(&t, "Multivariate Tests", &key, "Hypothesis df"),
                    w[3],
                    &what,
                );
                near(
                    value(&t, "Multivariate Tests", &key, "Error df"),
                    w[4],
                    &what,
                );
                near(value(&t, "Multivariate Tests", &key, "Sig."), w[5], &what);
            }
        }
    }
}

